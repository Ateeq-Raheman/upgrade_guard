"""Generates a tailored, step-by-step upgrade runbook (markdown)."""
import os
import subprocess

import frappe

from upgrade_guard.engine.constants import OFFICIAL_APPS, VERSIONED_OFFICIAL
from upgrade_guard.engine.rules import load_rules


def _branch(path):
	try:
		return subprocess.run(["git", "-C", path, "rev-parse", "--abbrev-ref", "HEAD"], capture_output=True, text=True, timeout=10).stdout.strip() or "(not a git repo)"
	except Exception:
		return "(unknown)"


def build(source, target):
	site = frappe.local.site
	rules, _ = load_rules(source, target)
	py = max((tuple(map(int, r["python_min"].split("."))) for r in rules if r.get("python_min")), default=None)
	node = max((int(r["node_min"]) for r in rules if r.get("node_min")), default=None)
	apps = frappe.get_installed_apps()
	custom = [a for a in apps if a not in OFFICIAL_APPS]
	versioned = [a for a in apps if a in VERSIONED_OFFICIAL]
	other_official = [a for a in apps if a in OFFICIAL_APPS and a not in VERSIONED_OFFICIAL]
	rows = "\n".join(f"| {a} | {_branch(os.path.dirname(frappe.get_app_path(a)))} | {'official' if a in OFFICIAL_APPS else 'custom'} |" for a in apps)
	L = [f"# Upgrade runbook: `{site}` v{source} → v{target}", "",
		"Generated by Upgrade Guard. **Rehearse the whole thing on a restored copy in a separate bench first.**", "",
		"## 0. Current state", "| App | Branch | Type |", "|---|---|---|", rows, "",
		"## 1. Preconditions"]
	if py:
		L.append(f"- Python **{'.'.join(map(str, py))}+** on the target bench host")
	if node:
		L.append(f"- Node.js **{node}+**")
	L += ["- Do not run `bench update`; branches are switched explicitly in step 4.",
		"- Fix every **blocker** and **high** finding (`bench --site %s upgrade-check --target %d --min-severity high`)." % (site, target),
		"- Preview auto-fixes: `bench --site %s upgrade-fix --target %d`; apply on a git branch of each custom app." % (site, target), "",
		"## 2. Backup (do not skip)",
		f"```\nbench --site {site} backup --with-files\ncp sites/{site}/site_config.json ~/site_config.{site}.bak\n```",
		"Verify the backup files exist in `sites/%s/private/backups/` and restore them once on a scratch site." % site, "",
		"## 3. Baseline snapshot (before)",
		f"```\nbench --site {site} upgrade-snapshot --out before.json --reports \"General Ledger::{{...}}\"\n```", "",
		"## 4. Switch code",
		f"```\nbench --site {site} set-maintenance-mode on"]
	if versioned:
		L.append(f"bench switch-to-branch version-{target} {' '.join(versioned)} --upgrade")
	L.append("```")
	for a in other_official:
		L.append(f"- `{a}`: official app with its own release line; pull the branch that supports Frappe v{target}.")
	for a in custom:
		L.append(f"- `{a}` (custom): make sure `pyproject.toml` allows `frappe>={target}.0.0-dev,<{target + 1}.0.0` and the fixes are merged.")
	L += ["", "## 5. Migrate and build",
		f"```\nbench setup requirements\nbench --site {site} migrate\nbench build\nbench restart\n```",
		"If migrate fails: read the traceback, note the app, restore from step 2 and fix before retrying.", "",
		"## 6. Verify (after)",
		f"```\nbench --site {site} upgrade-snapshot --out after.json --reports ...\nbench --site {site} upgrade-compare before.json after.json\nbench --site {site} set-maintenance-mode off\n```",
		"Then click through: login, a core transaction in each module, one print per custom format, one report per module.", "",
		"## 7. Rollback",
		f"```\nbench switch-to-branch version-{source} {' '.join(versioned)} --upgrade\nbench --site {site} --force restore <backup.sql.gz> --with-private-files <private.tar> --with-public-files <public.tar>\nbench setup requirements && bench build && bench restart\n```",
		"Keep the previous Python/Node available until the upgrade is signed off."]
	return "\n".join(L)
